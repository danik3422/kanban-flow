const LOCALES = { en: 'en-GB', uk: 'uk-UA', ru: 'ru-RU' }

export const localeOf = (language) => LOCALES[language] || LOCALES.en

/** Looks up a key like "verify.title" and fills its {placeholders}. */
export const translator = (language) => {
	const lang = STRINGS[language] ? language : 'en'
	const plural = new Intl.PluralRules(localeOf(lang))
	return (key, values = {}) => {
		const find = (dictionary) => key.split('.').reduce((node, part) => node?.[part], dictionary)
		let entry = find(STRINGS[lang]) ?? find(STRINGS.en) ?? key
		if (typeof entry === 'object') entry = entry[plural.select(values.count ?? 1)] ?? entry.other
		return String(entry).replace(/\{(\w+)\}/g, (match, name) => (values[name] ?? match))
	}
}
