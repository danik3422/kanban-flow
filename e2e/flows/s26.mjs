// The board's top bar: rename in place, star, visibility, Share (invite, link, roles,
// remove), the card filter with its shortcuts, the board menu (about, activity, copy,
// link, delete), a member's read-only view, and the phone layout.
import { APP, check, createVerifiedUser, done, launch, uiLogin, watch } from '../lib.mjs'

const stamp = Date.now()
const OWNER = { email: `head-owner-${stamp}@example.com`, password: 'Password123!', name: 'Olga Owner' }
const MEMBER = { email: `head-member-${stamp}@example.com`, password: 'Password123!', name: 'Max Member' }
const owner = await createVerifiedUser(OWNER, 'PM')
const member = await createVerifiedUser(MEMBER, 'Dev')
await owner.call('PATCH', '/auth/settings', { language: 'en' })
await member.call('PATCH', '/auth/settings', { language: 'en' })
const board = await owner.call('POST', '/board/boards', { name: 'Launch plan' })
const todo = await owner.call('POST', `/board/boards/${board._id}/columns`, { title: 'To do', position: 0 })
const done_ = await owner.call('POST', `/board/boards/${board._id}/columns`, { title: 'Done', position: 1 })
const join = await owner.call('POST', `/board/boards/${board._id}/invites`, { email: MEMBER.email, role: 'member' })
await member.call('POST', `/board/invites/${new URL(join.inviteUrl).pathname.split('/').pop()}/accept`)
const memberId = (await member.call('GET', '/auth/get-user'))._id
const ownerId = (await owner.call('GET', '/auth/get-user'))._id
const overdue = new Date(Date.now() - 3 * 86400000).toISOString().slice(0, 10)
await owner.call('POST', `/board/columns/${todo._id}/task`, { title: 'Design hero', labels: ['Design'], priority: 'high', assignees: [memberId] })
await owner.call('POST', `/board/columns/${todo._id}/task`, { title: 'Write copy', labels: ['Content'], dueDate: overdue, assignees: [ownerId] })
await owner.call('POST', `/board/columns/${done_._id}/task`, { title: 'Pick a domain', dueDate: overdue })

const browser = await launch()
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: APP })
const page = await ctx.newPage(); watch(page, 'owner')
await page.goto(`${APP}/login`); await uiLogin(page, OWNER.email, OWNER.password); await page.waitForURL(/\/workspaces/)
await page.goto(`${APP}/workspaces/${board._id}`); await page.waitForSelector('.task-card')
const visibleCards = () => page.locator('.task-card:visible').allInnerTexts()

// Rename in place.
await page.locator('.bh-title .bh-name').click()
await page.keyboard.press('ControlOrMeta+a'); await page.keyboard.type('Launch plan v2'); await page.keyboard.press('Escape')
check('Escape keeps the old name', (await page.locator('.bh-name').innerText()) === 'Launch plan')
await page.locator('.bh-title .bh-name').click()
await page.keyboard.press('ControlOrMeta+a'); await page.keyboard.type('Launch plan v2'); await page.keyboard.press('Enter')
await page.waitForTimeout(600)
check('Enter renames the board', (await owner.call('GET', `/board/boards/${board._id}`)).name === 'Launch plan v2' && (await page.locator('.bh-name').innerText()) === 'Launch plan v2')
check('the sidebar follows the new name', (await page.locator('.app-sidebar').innerText()).includes('Launch plan v2'))

// Star.
await page.getByRole('button', { name: 'Star board' }).first().click()
check('starring puts the board under Starred', (await page.locator('.app-sidebar__section', { hasText: 'Starred' }).getByText('Launch plan v2').count()) === 1)

// Visibility.
await page.locator('.bh-visibility').click()
await page.getByRole('menuitemradio', { name: 'Workspace' }).click()
await page.waitForTimeout(600)
check('visibility can be changed from the bar', (await owner.call('GET', `/board/boards/${board._id}`)).visibility === 'workspace' && (await page.locator('.bh-visibility').innerText()).includes('Workspace'))
await page.locator('.bh-visibility').click()
await page.getByRole('menuitemradio', { name: 'Public' }).click()
check('going public asks first', await page.getByRole('dialog').getByText('Make this board public?').isVisible())
await page.getByRole('dialog').getByRole('button', { name: 'Make public' }).click()
await page.waitForTimeout(600)
check('…and then it is public', (await owner.call('GET', `/board/boards/${board._id}`)).visibility === 'public')

// Share.
await page.locator('.bh-actions .bh-share').click()
await page.waitForSelector('.bh-share-body')
check('everyone on the board is listed with a role', (await page.locator('.bh-person').count()) === 2 && (await page.locator('.bh-person', { hasText: 'Olga Owner' }).innerText()).includes('Owner'))
await page.getByLabel('Email address').fill('not-an-email')
await page.getByRole('button', { name: 'Invite', exact: true }).click()
check('a wrong email is caught', (await page.locator('.bh-invite__error').innerText()).includes('valid email'))
const guestEmail = `guest-${stamp}@example.com`
await page.getByLabel('Email address').fill(guestEmail)
await page.getByRole('button', { name: 'Invite', exact: true }).click()
await page.waitForSelector(`.bh-person:has-text("${guestEmail}")`)
check('an invitation shows as waiting', (await page.locator('.bh-person', { hasText: guestEmail }).innerText()).includes('Waiting to accept'))
await page.locator('.bh-person', { hasText: guestEmail }).getByRole('button', { name: 'Cancel invitation' }).click()
await page.waitForTimeout(600)
check('an invitation can be cancelled', (await page.locator('.bh-person', { hasText: guestEmail }).count()) === 0)
await page.getByRole('button', { name: 'Create link', exact: true }).click()
await page.waitForTimeout(800)
check('an invite link is created and copied', (await page.evaluate(() => navigator.clipboard.readText())).includes('/invite/'))
check('the link can be turned off', (await page.locator('.bh-link-row', { hasText: 'Invite with a link' }).getByRole('button', { name: 'Turn off' }).count()) === 1)
await page.getByRole('button', { name: 'Create view link' }).click()
await page.waitForTimeout(800)
check('a public board offers a view link', (await page.evaluate(() => navigator.clipboard.readText())).includes('/public/'))
await page.getByLabel('Role of Max Member').selectOption('admin')
await page.waitForTimeout(600)
check('a role can be changed', (await owner.call('GET', `/board/boards/${board._id}/members`)).find((record) => record.user.email === MEMBER.email).role === 'admin')
await page.getByLabel('Role of Max Member').selectOption('member')
await page.waitForTimeout(400)
await page.keyboard.press('Escape')

// Filter.
await page.keyboard.press('f')
await page.waitForSelector('.bh-filter-body')
await page.locator('.bh-chips .ui-chip', { hasText: 'Design' }).click()
await page.waitForTimeout(300)
check('a label narrows the board', JSON.stringify(await visibleCards()).includes('Design hero') && !JSON.stringify(await visibleCards()).includes('Write copy'))
check('the panel counts matching cards', (await page.locator('.bh-filter-footer__count').innerText()) === '1 card matches')
await page.getByRole('button', { name: 'Clear filters' }).click()
await page.getByLabel('Overdue').check()
await page.waitForTimeout(300)
const overdueCards = JSON.stringify(await visibleCards())
check('Overdue skips cards already done', overdueCards.includes('Write copy') && !overdueCards.includes('Pick a domain'), overdueCards)
await page.getByRole('button', { name: 'Clear filters' }).click()
await page.locator('.bh-filter-body input[type=search]').fill('hero')
await page.waitForTimeout(300)
check('words find cards', (await visibleCards()).length === 1)
await page.keyboard.press('Escape')
check('the Filter button shows how many filters are on', (await page.locator('.bh-actions .bh-filter .bh-count').innerText()) === '1')
await page.locator('.bh-actions .bh-filter').click(); await page.getByRole('button', { name: 'Clear filters' }).click(); await page.keyboard.press('Escape')
await page.mouse.click(1100, 700)
await page.keyboard.press('q')
await page.waitForTimeout(300)
check('Q shows only my cards', JSON.stringify(await visibleCards()).includes('Write copy') && !JSON.stringify(await visibleCards()).includes('Design hero'))
await page.keyboard.press('q')
await page.waitForTimeout(300)
check('Q again shows everything', (await visibleCards()).length === 3)

// Board menu: about, activity, copy, link.
await page.locator('.bh-actions .bh-menu').click()
await page.waitForSelector('.bh-menu-body')
await page.locator('.bh-about').click()
await page.locator('.bh-menu-form textarea').fill('Everything for the Q4 launch.')
await page.getByRole('button', { name: 'Save' }).click()
await page.waitForTimeout(600)
check('the description is saved', (await owner.call('GET', `/board/boards/${board._id}`)).description === 'Everything for the Q4 launch.')
check('the menu shows it', (await page.locator('.bh-about__text').innerText()).includes('Q4 launch'))
await page.locator('.bh-menu-item', { hasText: 'Activity' }).click()
check('activity lists what happened', (await page.locator('.bh-activity__item').count()) >= 3 && (await page.locator('.bh-activity').innerText()).includes('renamed'))
await page.keyboard.press('Escape')
check('Escape steps back to the menu', await page.locator('.bh-menu-body').isVisible())
await page.locator('.bh-menu-item', { hasText: 'Copy link to board' }).click()
await page.waitForTimeout(400)
check('the board link is copied', (await page.evaluate(() => navigator.clipboard.readText())).endsWith(`/workspaces/${board._id}`))
await page.locator('.bh-menu-item', { hasText: 'Copy board' }).click()
check('the copy is named after the board', (await page.locator('.bh-menu-form input').first().inputValue()) === 'Launch plan v2 (copy)')
await page.getByRole('button', { name: 'Create copy' }).click()
await page.waitForURL((url) => url.pathname.startsWith('/workspaces/') && !url.pathname.endsWith(board._id), { timeout: 8000 })
await page.waitForSelector('.task-card')
check('the copy opens with the lists and cards', (await page.locator('.bc-board > .bc-column').count()) === 2 && (await page.locator('.task-card').count()) === 3 && (await page.locator('.bh-name').innerText()) === 'Launch plan v2 (copy)')
check('the copy is private', (await page.locator('.bh-visibility').innerText()).includes('Private'))

// Delete the copy: the name must be typed.
await page.locator('.bh-actions .bh-menu').click()
await page.locator('.bh-menu-item', { hasText: 'Delete board' }).click()
const deleteButton = page.getByRole('dialog').getByRole('button', { name: 'Delete board' })
check('delete waits for the board name', await deleteButton.isDisabled())
await page.getByRole('dialog').locator('input').fill('Launch plan v2 (copy)')
await deleteButton.click()
await page.waitForURL(/\/workspaces$/)
check('the copy is deleted', !(await page.locator('.app-sidebar').innerText()).includes('(copy)'))

// A member: no renaming, no inviting, Leave instead of Delete.
const memberCtx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const memberPage = await memberCtx.newPage(); watch(memberPage, 'member')
await memberPage.goto(`${APP}/login`); await uiLogin(memberPage, MEMBER.email, MEMBER.password); await memberPage.waitForURL(/\/workspaces/)
await memberPage.goto(`${APP}/workspaces/${board._id}`); await memberPage.waitForSelector('.task-card')
check('members cannot rename', (await memberPage.locator('h1.bh-name').count()) === 1 && (await memberPage.locator('button.bh-name').count()) === 0)
check('members see visibility but cannot change it', (await memberPage.locator('.bh-visibility.is-static').count()) === 1)
await memberPage.locator('.bh-actions .bh-share').click()
check('members see who is here, not invite', (await memberPage.locator('.bh-share-body').innerText()).includes('Only admins') && (await memberPage.getByLabel('Email address').count()) === 0)
await memberPage.keyboard.press('Escape')
await memberPage.locator('.bh-actions .bh-menu').click()
check('members can leave, not delete', (await memberPage.locator('.bh-menu-item', { hasText: 'Leave board' }).count()) === 1 && (await memberPage.locator('.bh-menu-item', { hasText: 'Delete board' }).count()) === 0)
await memberCtx.close()

// Phone.
const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, storageState: await ctx.storageState() })
const phonePage = await phone.newPage(); watch(phonePage, 'phone')
await phonePage.goto(`${APP}/workspaces/${board._id}`); await phonePage.waitForSelector('.task-card')
const nameFit = await phonePage.locator('.bh-name__text').evaluate((node) => ({ whole: node.scrollWidth <= node.clientWidth + 1, width: node.getBoundingClientRect().width }))
check('the board name has room on a phone', nameFit.whole || nameFit.width > 130, JSON.stringify(nameFit))
check('nothing spills sideways', await phonePage.evaluate(() => document.querySelector('.app-topbar').scrollWidth <= window.innerWidth))
await phonePage.locator('.bh-actions .bh-menu').click()
await phonePage.locator('.bh-menu-item', { hasText: 'Share and people' }).click()
check('Share is in the menu on a phone', await phonePage.locator('.bh-share-body').isVisible())
await phone.close()

await browser.close(); done()
