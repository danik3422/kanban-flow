import { APP, API, check, done, launch, watch, ALICE_STATE } from '../lib.mjs'
const browser = await launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, storageState: ALICE_STATE })
const page = await ctx.newPage(); watch(page, 'alice')
const board = await (await page.request.post(`${API}/board/boards`, { data: { name: `Close ${Date.now()}` } })).json()
const column = await (await page.request.post(`${API}/board/boards/${board._id}/columns`, { data: { title: 'Doomed' } })).json()
await page.request.post(`${API}/board/columns/${column._id}/task`, { data: { title: 'Open me' } })
await page.goto(`${APP}/workspaces/${board._id}`); await page.waitForTimeout(2000)
await page.locator('.task-card', { hasText: 'Open me' }).click()
await page.waitForSelector('#task-due-date')
const other = await ctx.newPage()
await other.request.delete(`${API}/board/columns/${column._id}`)
await page.waitForTimeout(1500)
check('task details close when a colleague deletes its column', (await page.locator('#task-due-date').count()) === 0)
await browser.close(); done()
