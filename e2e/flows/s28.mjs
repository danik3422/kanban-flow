// Cards: the face (labels, badges, complete), dragging within and across lists, and
// the card window — title, list, labels, dates, members, checklist, description,
// attachments, cover, time tracking, comments, watching, copy, move and delete.
import { APP, check, createVerifiedUser, done, launch, uiLogin, watch } from '../lib.mjs'

const stamp = Date.now()
const ME = { email: `cards-${stamp}@example.com`, password: 'Password123!', name: 'Cara Cards' }
const me = await createVerifiedUser(ME, 'PM')
await me.call('PATCH', '/auth/settings', { language: 'en' })
const meId = (await me.call('GET', '/auth/get-user'))._id
const board = await me.call('POST', '/board/boards', { name: 'Card lab' })
const todo = await me.call('POST', `/board/boards/${board._id}/columns`, { title: 'To do', position: 0 })
const doing = await me.call('POST', `/board/boards/${board._id}/columns`, { title: 'Doing', position: 1 })
await me.call('POST', `/board/boards/${board._id}/columns`, { title: 'Done', position: 2 })
for (const title of ['Alpha', 'Bravo', 'Charlie']) await me.call('POST', `/board/columns/${todo._id}/task`, { title })
const orderOf = async (columnId) => (await me.call('GET', `/board/boards/${board._id}/content`)).find((column) => column._id === columnId).tasks.map((task) => task.title)

const browser = await launch()
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: APP })
const page = await ctx.newPage(); watch(page, 'me')
await page.goto(`${APP}/login`); await uiLogin(page, ME.email, ME.password); await page.waitForURL(/\/workspaces/)
await page.goto(`${APP}/workspaces/${board._id}`); await page.waitForSelector('.task-card.ct')
const card = (title) => page.locator('.task-card.ct', { hasText: title }).first()
const listTitles = (index) => page.locator('.bc-board > .bc-column').nth(index).locator('.task-card.ct .ct-title').allInnerTexts()

// Dragging with a mouse.
let reorders = 0
page.on('request', (request) => { if (request.url().includes('/tasks/reorder')) reorders++ })
const drag = async (from, toX, toY, steps = 20) => {
	const box = await from.boundingBox()
	await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
	await page.mouse.down()
	await page.mouse.move(toX, toY, { steps })
}
const alpha = await card('Alpha').boundingBox()
await drag(card('Alpha'), alpha.x + alpha.width / 2 + 10, alpha.y + alpha.height / 2 + 6)
check('a lifted card follows as a tilted ghost', (await page.locator('.task-card--ghost.is-lifted').count()) === 1)
check('a slot opens where it would land', (await page.locator('.task-drag-slot').count()) === 1)
await page.mouse.up(); await page.waitForTimeout(500)
check('dropping it back sends nothing', reorders === 0)
const charlie = await card('Charlie').boundingBox()
await drag(card('Alpha'), charlie.x + charlie.width / 2, charlie.y + charlie.height - 2)
await page.waitForTimeout(250)
await page.mouse.up(); await page.waitForTimeout(700)
check('dragging down a list reorders it', (await listTitles(0)).join(',') === 'Bravo,Charlie,Alpha', (await listTitles(0)).join(','))
check('…and the order is saved', (await orderOf(todo._id)).join(',') === 'Bravo,Charlie,Alpha')
check('the ghost is gone after the drop', (await page.locator('.task-card--ghost').count()) === 0)
const doingList = await page.locator('.bc-board > .bc-column').nth(1).boundingBox()
await drag(card('Bravo'), doingList.x + doingList.width / 2, doingList.y + 80)
await page.waitForTimeout(250)
check('the target list is highlighted', (await page.locator('.bc-column.is-drop-target').count()) === 1)
await page.mouse.up(); await page.waitForTimeout(700)
check('dragging across lists moves the card', (await orderOf(doing._id)).join(',') === 'Bravo')
const beforeCancel = reorders
await drag(card('Charlie'), doingList.x + doingList.width / 2, doingList.y + 80)
await page.keyboard.press('Escape'); await page.mouse.up(); await page.waitForTimeout(400)
check('Escape cancels a drag', reorders === beforeCancel && (await listTitles(0)).includes('Charlie'))

// Complete from the face.
await card('Charlie').hover()
await card('Charlie').getByRole('button', { name: 'Mark complete' }).click()
await page.waitForTimeout(600)
check('the round button marks a card complete', (await me.call('GET', `/board/boards/${board._id}/content`))[0].tasks.find((task) => task.title === 'Charlie').completed === true)

// The card window.
await card('Alpha').click()
await page.waitForSelector('.cm-modal')
check('the window shows the list it is in', (await page.locator('.cm-list-button').innerText()).includes('To do'))
check('comments are beside the card on wide screens', await page.locator('.cm-side').isVisible())
const title = page.getByLabel('Card title')
await title.fill('Alpha launch'); await title.press('Enter')
await page.waitForTimeout(600)
check('the title saves on Enter', (await orderOf(todo._id)).includes('Alpha launch'))

// Labels: create (lands on the card), then rename everywhere.
await page.getByRole('button', { name: 'Labels', exact: true }).click()
await page.getByRole('button', { name: 'Create a new label' }).click()
await page.locator('.cp').getByLabel('Name').fill('Launch')
await page.locator('.cp').getByRole('radio', { name: 'Purple' }).click()
await page.locator('.cp').getByRole('button', { name: 'Create a new label' }).click()
await page.waitForTimeout(600)
check('a new label goes on the board and the card', (await me.call('GET', `/board/boards/${board._id}`)).labels.some((label) => label.name === 'Launch' && label.color === 'purple') && (await card('Alpha launch').locator('.ct-label').innerText()) === 'Launch')
await page.locator('.cp').getByRole('button', { name: 'Edit label Launch' }).click()
await page.locator('.cp').getByLabel('Name').fill('Release')
await page.locator('.cp').getByRole('button', { name: 'Save' }).click()
await page.waitForTimeout(600)
check('renaming a label renames it on cards', (await card('Alpha launch').locator('.ct-label').innerText()) === 'Release')
await page.keyboard.press('Escape')
check('Escape closes the panel, not the card', await page.locator('.cm-modal').isVisible() && (await page.locator('.cp').count()) === 0)

// Dates, members, priority.
await page.getByRole('button', { name: 'Dates', exact: true }).click()
await page.locator('.cp').getByRole('button', { name: 'Tomorrow' }).click()
await page.locator('.cp').getByRole('button', { name: 'Save' }).click()
await page.waitForTimeout(600)
check('a due date shows as due soon', (await page.locator('.cm-date').innerText()).includes('Due soon') && (await card('Alpha launch').locator('.ct-due--soon').count()) === 1)
await page.getByRole('button', { name: 'Members', exact: true }).click()
await page.locator('.cp').getByRole('button', { name: /Cara Cards/ }).click()
await page.waitForTimeout(600)
await page.keyboard.press('Escape')
check('a member shows on the card', (await card('Alpha launch').locator('.ct-people').count()) === 1)

// Checklist and description.
await page.getByRole('button', { name: 'Checklist', exact: true }).click()
const item = page.getByLabel('Add an item')
await item.fill('Write notes'); await item.press('Enter')
await item.fill('Ship it'); await item.press('Enter')
await page.waitForTimeout(600)
await page.locator('.cm-check').first().locator('input[type=checkbox]').check()
await page.waitForTimeout(600)
check('the checklist shows progress on the face', (await card('Alpha launch').innerText()).includes('1/2'))
await page.locator('.cm-description-empty').click()
await page.locator('.cm-description-editor [contenteditable]').fill('Everything for the launch')
await page.locator('.cm-description-editor').getByRole('button', { name: 'Save' }).click()
await page.waitForTimeout(600)
check('the description saves', (await page.locator('.cm-description').innerText()).includes('Everything for the launch'))

// Attachment and cover.
await page.getByRole('button', { name: 'Attachment', exact: true }).click()
await page.locator('.cp').getByLabel('Paste a link').fill('https://www.figma.com/file/launch')
await page.locator('.cp').getByLabel('Display text (optional)').fill('Mockups')
await page.locator('.cp').getByRole('button', { name: 'Insert' }).click()
await page.waitForTimeout(700)
check('a link is attached', (await page.locator('.cm-attachment').innerText()).includes('Mockups') && (await card('Alpha launch').innerText()).includes('1'))
await page.getByRole('button', { name: 'Cover', exact: true }).click()
await page.locator('.cp').getByRole('radio', { name: 'Blue' }).click()
await page.waitForTimeout(600)
check('a colour cover shows on the card', (await card('Alpha launch').locator('.ct-cover').count()) === 1)
await page.locator('.cp').getByRole('button', { name: /Fill the card/ }).click()
await page.waitForTimeout(600)
check('the cover can fill the card', await card('Alpha launch').evaluate((node) => node.classList.contains('ct--full')))
await page.keyboard.press('Escape')

// Time tracking.
await page.getByRole('button', { name: 'Start timer' }).click()
await page.waitForTimeout(1500)
check('a running timer shows on the card face', (await card('Alpha launch').locator('.ct-timer.is-running').count()) === 1)
await page.getByRole('button', { name: /Stop timer/ }).click()
await page.waitForTimeout(800)
await page.getByLabel('Time spent').fill('1h 30m')
await page.locator('.cm-time__add').getByRole('button', { name: 'Add time' }).click()
await page.waitForTimeout(800)
check('time added by hand counts', (await page.locator('.cm-time__totals').innerText()).includes('1 h 30 m'))
await page.locator('.cm-estimate').click()
await page.getByLabel('Estimate').fill('2h'); await page.getByLabel('Estimate').press('Enter')
await page.waitForTimeout(700)
check('the estimate shows what is left', (await page.locator('.cm-time').innerText()).includes('left'))
check('entries list who logged what', (await page.locator('.cm-entry').count()) >= 2)

// Comments.
await page.getByLabel('Write a comment…').fill('Looks great')
await page.locator('.cc__composer').getByRole('button', { name: 'Save' }).click()
await page.waitForTimeout(700)
check('a comment appears and counts on the face', (await page.locator('.cc__comment').innerText()).includes('Looks great') && (await card('Alpha launch').innerText()).includes('1'))
await page.locator('.cc__comment').getByRole('button', { name: 'Edit' }).click()
await page.getByLabel('Edit comment').fill('Looks great!')
await page.locator('.cc__edit').getByRole('button', { name: 'Save' }).click()
await page.waitForTimeout(600)
check('a comment can be edited', (await page.locator('.cc__comment').innerText()).includes('(edited)'))
await page.getByRole('button', { name: 'Show activity' }).click()
check('details show the history in words', (await page.locator('.cc__event').count()) > 3 && (await page.locator('.cc').innerText()).includes('changed the'))
await page.locator('.cc__comment').getByRole('button', { name: 'Delete comment' }).click()
await page.getByRole('dialog').last().getByRole('button', { name: 'Delete comment' }).click()
await page.waitForTimeout(600)
check('a comment can be deleted', (await page.locator('.cc__comment').count()) === 0)
await page.locator('.cm-comments-toggle').click()
check('the Comments button hides the panel', (await page.locator('.cm-side').count()) === 0)
await page.locator('.cm-comments-toggle').click()

// Watch, list menu, copy, delete.
await page.getByRole('button', { name: 'Card actions' }).click()
await page.getByRole('menuitem', { name: 'Watch' }).click()
await page.waitForTimeout(600)
check('watching shows on the card', (await card('Alpha launch').getByLabel('You are watching this card').count()) === 1)
await page.locator('.cm-list-button').click()
await page.getByRole('menuitemradio', { name: 'Doing' }).click()
await page.waitForTimeout(800)
check('the list button moves the card', (await orderOf(doing._id)).includes('Alpha launch') && (await page.locator('.cm-list-button').innerText()).includes('Doing'))
await page.getByRole('button', { name: 'Card actions' }).click()
await page.getByRole('menuitem', { name: 'Copy card' }).click()
await page.locator('.cp').getByRole('button', { name: 'Create card' }).click()
await page.waitForTimeout(900)
check('a card can be copied with its checklist', (await orderOf(doing._id)).includes('Alpha launch (copy)') && (await card('Alpha launch (copy)').innerText()).includes('1/2'))
await page.getByRole('button', { name: 'Card actions' }).click()
await page.getByRole('menuitem', { name: 'Delete card' }).click()
await page.getByRole('dialog').last().getByRole('button', { name: 'Delete card' }).click()
await page.waitForTimeout(800)
check('a card can be deleted from its window', (await page.locator('.cm-modal').count()) === 0 && !(await orderOf(doing._id)).includes('Alpha launch'))

// Phone: the card is a sheet, Comments switches to the comments view.
for (const title of ['Delta', 'Echo']) await me.call('POST', `/board/columns/${todo._id}/task`, { title })
const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, storageState: await ctx.storageState() })
const phonePage = await phone.newPage(); watch(phonePage, 'phone')
await phonePage.goto(`${APP}/workspaces/${board._id}`); await phonePage.waitForSelector('.task-card.ct')
// A finger: a quick swipe scrolls, a press and hold picks the card up.
const cdp = await phone.newCDPSession(phonePage)
const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
const firstBox = await phonePage.locator('.bc-board > .bc-column').first().locator('.task-card.ct').first().boundingBox()
const lastBox = await phonePage.locator('.bc-board > .bc-column').first().locator('.task-card.ct').last().boundingBox()
const tx = firstBox.x + firstBox.width / 2, ty = firstBox.y + firstBox.height / 2
await touch('touchStart', tx, ty)
for (let step = 1; step <= 5; step++) await touch('touchMove', tx - step * 12, ty)
await touch('touchEnd')
await phonePage.waitForTimeout(300)
check('a quick swipe does not pick a card up', (await phonePage.locator('.task-card--ghost').count()) === 0)
const firstTitle = await phonePage.locator('.bc-board > .bc-column').first().locator('.ct-title').first().innerText()
await touch('touchStart', tx, ty)
await phonePage.waitForTimeout(450)
check('press and hold picks a card up', (await phonePage.locator('.task-card--ghost').count()) === 1)
for (let step = 1; step <= 15; step++) await touch('touchMove', tx, ty + ((lastBox.y + lastBox.height - 4 - ty) * step) / 15)
await touch('touchEnd')
await phonePage.waitForTimeout(800)
const afterTouch = await phonePage.locator('.bc-board > .bc-column').first().locator('.ct-title').allInnerTexts()
check('a finger drag moves the card down the list', afterTouch.length === 3 && afterTouch.at(-1) === firstTitle && afterTouch[0] !== firstTitle && (await phonePage.locator('.cm-modal').count()) === 0, afterTouch.join(','))
await phonePage.locator('.task-card.ct').first().tap()
await phonePage.waitForSelector('.cm-modal')
check('a phone opens the card without comments first', (await phonePage.locator('.cm-side').count()) === 0)
check('the add buttons stay full size on a phone', (await phonePage.locator('.cm-actions .ui-btn').first().boundingBox()).height >= 32)
await phonePage.locator('.cm-dock__button').last().tap()
check('Comments switches to the comments view', (await phonePage.locator('.cm-side').isVisible()) && (await phonePage.locator('.cm-main').count()) === 0)
check('nothing spills sideways', await phonePage.evaluate(() => document.querySelector('.cm-modal').scrollWidth <= window.innerWidth))
await phone.close()

await browser.close(); done()
